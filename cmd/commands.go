package cmd

import (
	"fmt"
	"os"
	"strings"
	"time"

	"github.com/spf13/cobra"

	utils "github.com/jlkendrick/grimoire/internal/utils"
	cache "github.com/jlkendrick/grimoire/internal/cache"
	desc "github.com/jlkendrick/grimoire/internal/descriptor"
	runtime "github.com/jlkendrick/grimoire/internal/runtime"
	extract "github.com/jlkendrick/grimoire/internal/extract"
)

func GenerateCommands(descriptor_cache *cache.DescriptorCache) ([]*cobra.Command, error) {
	commands := []*cobra.Command{}

	for _, descriptor := range descriptor_cache.Functions {
		var resolved_descriptor desc.FunctionDescriptor
		command := &cobra.Command{
			Use: descriptor.CommandName,
			Run: func(cmd *cobra.Command, args []string) {
				// Pre-run: check if the function descriptor is stale relative to the source code or the user's scroll.yaml file
				source_hash, err := utils.HashFile(descriptor.SourceFile)
				if err != nil {
					fmt.Fprintf(os.Stderr, "Error hashing source file: %v\n", err)
					os.Exit(1)
				}

				if source_hash != descriptor_cache.SourceHash {
					fmt.Fprintf(os.Stderr, "Source file has changed since last run. Updating runtime config...\n")
					// Re-extract the function descriptor
					function_descriptor_generator := extract.FunctionDescriptorGenerator{
						AbsPathToFunction: descriptor.SourceFile,
						FunctionName:   	 descriptor.FunctionName,
					}
					resolved_descriptor, err = function_descriptor_generator.GenerateDescriptor()
					if err != nil {
						fmt.Fprintf(os.Stderr, "Error generating spell descriptor: %v\n", err)
						os.Exit(1)
					}
					// Cache the resolved descriptor
					cache.AddFunctionDescriptor(resolved_descriptor)
				} else {
					// Use the cached descriptor
					resolved_descriptor = descriptor
				}

				payload := buildPayload(resolved_descriptor, cmd)

				start := time.Now()
				runResult, err := runtime.Run(&resolved_descriptor, payload)
				elapsed := time.Since(start)
				if err != nil {
					fmt.Fprintf(os.Stderr, "Error executing function: %v\n", err)
					os.Exit(1)
				}

				fmt.Println(string(runResult.Output))

				footerParts := []string{fmt.Sprintf("%.2fs", elapsed.Seconds())}
				if runResult.CacheStatus != "" {
					footerParts = append(footerParts, runResult.CacheStatus)
				}
				if runResult.Runtime != "" {
					footerParts = append(footerParts, runResult.Runtime)
				}
				fmt.Fprintf(os.Stderr, "\n%s %s\n", accent_style("◈"), dim_style(strings.Join(footerParts, " · ")))
			},
		}

		for _, param := range resolved_descriptor.Params {
			// Types might be wrong here if not generated by the init command, but we just assume the user knows what they're doing.
			// We do need to check if the default value corresponds to the type and give a helpful error message if not.
			switch param.ResolvedType.Kind {

			case "string", "str":
				if param.Default == nil {
					command.Flags().StringP(param.Name, "", "", "")
					command.MarkFlagRequired(param.Name)
					continue
				}
				if _, ok := param.Default.(string); !ok {
					return nil, fmt.Errorf("default value for %s is not a string", param.Name)
				}
				command.Flags().StringP(param.Name, "", param.Default.(string), "")

			case "integer", "int":
				if param.Default == nil {
					command.Flags().IntP(param.Name, "", 0, "")
					command.MarkFlagRequired(param.Name)
					continue
				}
				if _, ok := param.Default.(int); !ok {
					return nil, fmt.Errorf("default value for %s is not an int", param.Name)
				}
				command.Flags().IntP(param.Name, "", param.Default.(int), "")

			case "boolean", "bool":
				if param.Default == nil {
					command.Flags().BoolP(param.Name, "", false, "")
					command.MarkFlagRequired(param.Name)
					continue
				}
				if _, ok := param.Default.(bool); !ok {
					return nil, fmt.Errorf("default value for %s is not a bool", param.Name)
				}
				command.Flags().BoolP(param.Name, "", param.Default.(bool), "")

			case "float":
				if param.Default == nil {
					command.Flags().Float64P(param.Name, "", 0.0, "")
					command.MarkFlagRequired(param.Name)
					continue
				}
				if _, ok := param.Default.(float64); !ok {
					return nil, fmt.Errorf("default value for %s is not a float64", param.Name)
				}
				command.Flags().Float64P(param.Name, "", param.Default.(float64), "")

			default:
				return nil, fmt.Errorf("unsupported type: %s", param.ResolvedType.Kind)
			}
		}

		commands = append(commands, command)
	}

	return commands, nil
}

func buildPayload(descriptor desc.FunctionDescriptor, cmd *cobra.Command) map[string]interface{} {
	// Initialize the dynamic payload map
	payload := make(map[string]interface{})

	// Loop through the YAML params for this specific function
	for _, param := range descriptor.Params {
		// Must match the type strings used in GenerateCommands (including aliases like str/int/bool).
		switch param.ResolvedType.Kind {
		case "integer", "int":
			val, _ := cmd.Flags().GetInt(param.Name)
			payload[param.Name] = val
		case "string", "str":
			val, _ := cmd.Flags().GetString(param.Name)
			payload[param.Name] = val
		case "boolean", "bool":
			val, _ := cmd.Flags().GetBool(param.Name)
			payload[param.Name] = val
		case "float":
			val, _ := cmd.Flags().GetFloat64(param.Name)
			payload[param.Name] = val
		}
	}

	return payload
}