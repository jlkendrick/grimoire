func TestBuildPipeline_GraphDiamondEdges(t *testing.T) {
	var calls fakeCalls
	env := fakeEnv(nil, nil, &calls)
	g := mustBuild(t, &ir.Pipeline{Command: "ship", Mode: ir.ModeGraph, Steps: []ir.Step{
		{Spell: "checkout", Id: "src"},
		{Spell: "test", Id: "unit", Params: map[string]any{"tree": "src.path"}},
		{Spell: "lint", Id: "style", Params: map[string]any{"tree": "src.path"}},
		{Spell: "package", Id: "image", Params: map[string]any{"tree": "src.path", "passed": "unit.ok", "clean": "style.ok"}},
		{Print: "image.done"},
	}}, env)

	if n := nodeByID(t, g, "src"); n.Input.Kind != InputSeed || len(n.Deps) != 0 {
		t.Errorf("ref-less node: input %v deps %v, want Seed at the front", n.Input.Kind, n.Deps)
	}
	if n := nodeByID(t, g, "unit"); !slices.Equal(n.Deps, []string{"src"}) {
		t.Errorf("unit deps = %v, want [src]", n.Deps)
	}
	if n := nodeByID(t, g, "image"); !slices.Equal(n.Deps, []string{"src", "style", "unit"}) {
		t.Errorf("join deps = %v, want [src style unit]", n.Deps)
	}
}

