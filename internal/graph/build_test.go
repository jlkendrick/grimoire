func TestBuildFunction_SpellIsOneNodePlusPrint(t *testing.T) {
	var calls fakeCalls
	env := fakeEnv(map[string]any{"greet": "hello"}, nil, &calls)

	fn, _ := env.ResolveSpell("greet")
	g := BuildFunction(fn, env)
	if len(g.Nodes) != 2 {
		t.Fatalf("nodes = %v, want spell + print", nodeIDs(g))
	}

	out, err := Run(context.Background(), g, map[string]any{"name": "james"})
	if err != nil {
		t.Fatal(err)
	}
	if !slices.Equal(calls.prints, []any{"hello"}) {
		t.Errorf("prints = %v, want [hello]", calls.prints)
	}
	if out != "hello" {
		t.Errorf("out = %v, want the print node's passthrough", out)
	}
	if got := calls.payloads["greet"]; got["name"] != "james" {
		t.Errorf("payload = %v, want the seed flags", got)
	}
}
