func TestBuildPipeline_BranchModeInheritanceAndOverride(t *testing.T) {
	var calls fakeCalls
	env := fakeEnv(nil, nil, &calls)
	g := mustBuild(t, &ir.Pipeline{Command: "r", Mode: ir.ModeGraph, Steps: []ir.Step{
		{Spell: "gate", Id: "gate"},
		{If: "gate.ok", Then: []ir.Step{ // inherits graph
			{Spell: "t1", Id: "t1"},
			{Spell: "t2", Id: "t2"},
		}},
		{If: "gate.ok", Mode: ir.ModePipe, Then: []ir.Step{ // overrides to pipe
			{Spell: "p1"},
			{Spell: "p2"},
		}},
	}}, env)

	var ifNodes []*Node
	for _, n := range g.Nodes {
		if _, ok := n.Op.(*IfOp); ok {
			ifNodes = append(ifNodes, n)
		}
	}
	if len(ifNodes) != 2 {
		t.Fatalf("if nodes = %d, want 2", len(ifNodes))
	}
	// Both if-nodes read gate.ok, so both must wait on gate.
	for _, n := range ifNodes {
		if !slices.Contains(n.Deps, "gate") {
			t.Errorf("if node %s deps = %v, want gate from condition ref", n.ID, n.Deps)
		}
	}

	inherited := ifNodes[0].Op.(*IfOp).Then
	if len(inherited.Nodes[0].Deps) != 0 || len(inherited.Nodes[1].Deps) != 0 {
		t.Error("inherited graph branch: independent spells must have no edges between them")
	}
	overridden := ifNodes[1].Op.(*IfOp).Then
	if !slices.Equal(overridden.Nodes[1].Deps, []string{overridden.Nodes[0].ID}) {
		t.Errorf("pipe-overridden branch: second node deps = %v, want chain on first", overridden.Nodes[1].Deps)
	}
}

func TestBuildPipeline_GraphBranchFreeRefsBecomeIfDeps(t *testing.T) {
	var calls fakeCalls
	env := fakeEnv(nil, nil, &calls)
	g := mustBuild(t, &ir.Pipeline{Command: "r", Mode: ir.ModeGraph, Steps: []ir.Step{
		{Spell: "a", Id: "gate"},
		{Spell: "b", Id: "data"},
		{If: "gate.ok", Then: []ir.Step{
			{Spell: "use", Params: map[string]any{"v": "data.val"}}, // free ref to sibling
			{Let: "inner", Value: "1 > 0"},
			{Spell: "own", Params: map[string]any{"v": "inner"}}, // branch-bound, not free
		}},
	}}, env)

	var ifNode *Node
	for _, n := range g.Nodes {
		if _, ok := n.Op.(*IfOp); ok {
			ifNode = n
		}
	}
	if ifNode == nil {
		t.Fatal("no if node built")
	}
	if !slices.Contains(ifNode.Deps, "gate") || !slices.Contains(ifNode.Deps, "data") {
		t.Errorf("if deps = %v, want condition ref gate and branch free ref data", ifNode.Deps)
	}
	if len(ifNode.Deps) != 2 {
		t.Errorf("if deps = %v: branch-internal binding must not create an edge", ifNode.Deps)
	}
}

func TestBuildPipeline_Errors(t *testing.T) {
	var calls fakeCalls
	env := fakeEnv(nil, nil, &calls)

	for _, tc := range []struct {
		name string
		p    *ir.Pipeline
		want string
	}{
		{"empty", &ir.Pipeline{Command: "r"}, "no steps"},
		{"first not spell", &ir.Pipeline{Command: "r", Steps: []ir.Step{{Let: "x", Value: "1"}}}, "first step must be a spell"},
		{"unknown mode", &ir.Pipeline{Command: "r", Mode: "parallel", Steps: []ir.Step{{Spell: "a"}}}, "unknown mode"},
		{"mode on spell", &ir.Pipeline{Command: "r", Steps: []ir.Step{{Spell: "a", Mode: ir.ModePipe}}}, "only valid on rituals and if-steps"},
		{"empty then", &ir.Pipeline{Command: "r", Steps: []ir.Step{{Spell: "a"}, {If: "true", Then: nil}}}, "must be non-empty"},
		{
			"graph cycle",
			&ir.Pipeline{Command: "r", Mode: ir.ModeGraph, Steps: []ir.Step{
				{Spell: "s", Id: "a", Params: map[string]any{"v": "b.x"}},
				{Spell: "s", Id: "b", Params: map[string]any{"v": "a.x"}},
			}},
			"cycle",
		},
		{
			"graph duplicate binding",
			&ir.Pipeline{Command: "r", Mode: ir.ModeGraph, Steps: []ir.Step{
				{Spell: "s", Id: "x"},
				{Let: "x", Value: "1 > 0"},
			}},
			"bound by both",
		},
	} {
		t.Run(tc.name, func(t *testing.T) {
			if _, err := BuildPipeline(tc.p, env); err == nil || !strings.Contains(err.Error(), tc.want) {
				t.Fatalf("err = %v, want %q", err, tc.want)
			}
		})
	}
}

