// fakeCalls records what a built graph did: every spell payload and every
// printed value, in order.
type fakeCalls struct {
	mu       sync.Mutex
	payloads map[string]map[string]any
	prints   []any
}

// fakeEnv wires canned spell outputs (keyed by spell name) into an Env.
// params optionally gives a spell a signature, for chained adaptation.
func fakeEnv(outputs map[string]any, params map[string][]ir.Param, calls *fakeCalls) Env {
	calls.payloads = make(map[string]map[string]any)
	return Env{
		ResolveSpell: func(name string) (*ir.Function, error) {
			return &ir.Function{CommandName: name, Params: params[name]}, nil
		},
		RunSpell: func(_ context.Context, fn *ir.Function, payload map[string]any) (any, error) {
			calls.mu.Lock()
			calls.payloads[fn.CommandName] = payload
			calls.mu.Unlock()
			return outputs[fn.CommandName], nil
		},
		Present: func(v any) error {
			calls.mu.Lock()
			calls.prints = append(calls.prints, v)
			calls.mu.Unlock()
			return nil
		},
	}
}

func mustBuild(t *testing.T, p *ir.Pipeline, env Env) *Graph {
	t.Helper()
	g, err := BuildPipeline(p, env)
	if err != nil {
		t.Fatal(err)
	}
	return g
}

func nodeByID(t *testing.T, g *Graph, id string) *Node {
	t.Helper()
	for _, n := range g.Nodes {
		if n.ID == id {
			return n
		}
	}
	t.Fatalf("node %q not found in %v", id, nodeIDs(g))
	return nil
}

func nodeIDs(g *Graph) []string {
	ids := make([]string, len(g.Nodes))
	for i, n := range g.Nodes {
		ids[i] = n.ID
	}
	return ids
}

func TestBuildPipeline_PipeChainShape(t *testing.T) {
	var calls fakeCalls
	env := fakeEnv(nil, nil, &calls)
	g := mustBuild(t, &ir.Pipeline{Command: "r", Steps: []ir.Step{
		{Spell: "a"},
		{Spell: "b", Id: "bee", Params: map[string]any{"x": 1}},
		{Spell: "c"},
	}}, env)

	if len(g.Nodes) != 4 {
		t.Fatalf("nodes = %v, want 3 spells + autogenerated print", nodeIDs(g))
	}
	a, b, c, p := g.Nodes[0], g.Nodes[1], g.Nodes[2], g.Nodes[3]

	if a.Input.Kind != InputSeed || len(a.Deps) != 0 {
		t.Errorf("first node: input %v deps %v, want Seed and no deps", a.Input.Kind, a.Deps)
	}
	if b.ID != "bee" || b.Input.Kind != InputParams || !slices.Equal(b.Deps, []string{a.ID}) {
		t.Errorf("params step: id %q input %v deps %v", b.ID, b.Input.Kind, b.Deps)
	}
	if c.Input.Kind != InputChain || !slices.Equal(c.Deps, []string{"bee"}) {
		t.Errorf("chain step: input %v deps %v", c.Input.Kind, c.Deps)
	}
	if !c.Op.(*SpellOp).Chained || a.Op.(*SpellOp).Chained || b.Op.(*SpellOp).Chained {
		t.Error("Chained must be set exactly on chain-input spells")
	}
	if _, ok := p.Op.(*PrintOp); !ok || g.Out != p.ID || !slices.Equal(p.Deps, []string{c.ID}) {
		t.Errorf("tail: %T deps %v out %q, want auto-print chained to c", p.Op, p.Deps, g.Out)
	}
}

func TestBuildPipeline_BranchEntrySpellAdaptsChained(t *testing.T) {
	var calls fakeCalls
	env := fakeEnv(nil, nil, &calls)
	g := mustBuild(t, &ir.Pipeline{Command: "r", Steps: []ir.Step{
		{Id: "check", Spell: "status"},
		{If: "check.ok", Then: []ir.Step{{Spell: "handle"}}},
	}}, env)

	// The root entry takes the flags payload directly; a branch entry's
	// seed is an upstream return value, so a no-params branch entry must
	// adapt it like a chained input (a zero-param spell gets {}, not the
	// whole upstream map as kwargs).
	if g.Nodes[0].Op.(*SpellOp).Chained {
		t.Error("root entry spell must take the flags payload directly")
	}
	var ifNode *Node
	for _, n := range g.Nodes {
		if _, ok := n.Op.(*IfOp); ok {
			ifNode = n
		}
	}
	if ifNode == nil {
		t.Fatal("no if node built")
	}
	if !ifNode.Op.(*IfOp).Then.Nodes[0].Op.(*SpellOp).Chained {
		t.Error("branch entry spell without params must adapt its seed as a chained input")
	}
}

