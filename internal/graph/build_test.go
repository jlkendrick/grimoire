func TestExecute_GraphDiamondJoins(t *testing.T) {
	var calls fakeCalls
	env := fakeEnv(map[string]any{
		"checkout": map[string]any{"path": "/src"},
		"test":     map[string]any{"ok": true},
		"lint":     map[string]any{"ok": true},
		"package":  map[string]any{"done": true},
	}, nil, &calls)

	g := mustBuild(t, &ir.Pipeline{Command: "ship", Mode: ir.ModeGraph, Steps: []ir.Step{
		{Spell: "checkout", Id: "src"},
		{Spell: "test", Id: "unit", Params: map[string]any{"tree": "src.path"}},
		{Spell: "lint", Id: "style", Params: map[string]any{"tree": "src.path"}},
		{Spell: "package", Id: "image", Params: map[string]any{"tree": "src.path", "passed": "unit.ok", "clean": "style.ok"}},
		{Print: "image.done"},
	}}, env)

	if _, err := Run(context.Background(), g, nil); err != nil {
		t.Fatal(err)
	}
	if !slices.Equal(calls.prints, []any{true}) {
		t.Errorf("prints = %v, want [true]", calls.prints)
	}
	want := map[string]any{"tree": "/src", "passed": true, "clean": true}
	got := calls.payloads["package"]
	for k, v := range want {
		if got[k] != v {
			t.Errorf("join payload[%s] = %v, want %v (full: %v)", k, got[k], v, got)
		}
	}
}

